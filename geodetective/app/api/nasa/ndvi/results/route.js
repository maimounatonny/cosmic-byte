
const NASA_API_URL =
  "https://appeears.earthdatacloud.nasa.gov/api/";

async function getNasaToken() {
  const username = process.env.NASA_EARTHDATA_USERNAME;
  const password = process.env.NASA_EARTHDATA_PASSWORD;

  if (!username || !password) {
    throw new Error("NASA credentials are missing.");
  }

  const credentials = Buffer.from(
    `${username}:${password}`
  ).toString("base64");

  const response = await fetch(`${NASA_API_URL}login`, {
    method: "POST",
    headers: {
      Authorization: `Basic ${credentials}`,
      "Content-Type":
        "application/x-www-form-urlencoded;charset=UTF-8",
    },
    body: "grant_type=client_credentials",
    cache: "no-store",
  });

  const data = await response.json();

  if (!response.ok || !data.token) {
    throw new Error("NASA authentication failed.");
  }

  return data.token;
}

export async function GET(request) {
  try {
    const { searchParams } = new URL(request.url);
    const taskId = searchParams.get("taskId");

    if (!taskId || !/^[a-f0-9-]{36}$/i.test(taskId)) {
      return Response.json(
        {
          success: false,
          message: "A valid NASA task ID is required.",
        },
        { status: 400 }
      );
    }

    const token = await getNasaToken();

    // Check that NASA has completed the task.
    const statusResponse = await fetch(
      `${NASA_API_URL}task/${encodeURIComponent(taskId)}`,
      {
        headers: {
          Authorization: `Bearer ${token}`,
        },
        cache: "no-store",
      }
    );

    const statusData = await statusResponse.json();

    if (!statusResponse.ok) {
      return Response.json(
        {
          success: false,
          message: "Could not check NASA task status.",
        },
        { status: 502 }
      );
    }

    if (statusData.status !== "done") {
      return Response.json({
        success: false,
        status: statusData.status,
        message: "NASA has not finished processing this task.",
      }, { status: 202 });
    }

    // Retrieve the files generated by NASA.
    const bundleResponse = await fetch(
      `${NASA_API_URL}bundle/${encodeURIComponent(taskId)}`,
      {
        headers: {
          Authorization: `Bearer ${token}`,
        },
        cache: "no-store",
      }
    );

    const bundleData = await bundleResponse.json();

    if (!bundleResponse.ok) {
      console.error("NASA bundle error:", bundleData);

      return Response.json(
        {
          success: false,
          message: "Could not retrieve NASA result files.",
        },
        { status: 502 }
      );
    }

    const files = (bundleData.files || []).map((file) => ({
      fileId: file.file_id,
      fileName: file.file_name,
      fileType: file.file_type,
      fileSize: file.file_size,
    }));

    return Response.json({
      success: true,
      taskId,
      status: "done",
      totalFiles: files.length,
      files,
    });
  } catch (error) {
    console.error("NASA results error:", error);

    return Response.json(
      {
        success: false,
        message: error.message || "Could not retrieve NASA results.",
      },
      { status: 500 }
    );
  }
}
